def wheel(draw: ImageDraw.ImageDraw, x: int, y: int, radius=39):
    draw.ellipse((x-radius, y-radius, x+radius, y+radius), fill=INK)
    draw.ellipse((x-radius+10, y-radius+10, x+radius-10, y+radius-10), fill="#AEB6A5", outline=OLIVE, width=3)
    draw.ellipse((x-9, y-9, x+9, y+9), fill=OLIVE)
    for dx, dy in ((-17, 0), (17, 0), (0, -17), (0, 17)):
        draw.ellipse((x+dx-3, y+dy-3, x+dx+3, y+dy+3), fill=PAPER)


