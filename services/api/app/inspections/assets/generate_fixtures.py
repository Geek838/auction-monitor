def generate():
    entries = []
    specs = [
        ("front-illustration-v1", "Front-quarter illustration", "FRONT_QUARTER", front,
         "Project-authored front-quarter vehicle illustration with a rust-colored drawn bumper mark; not an auction photo."),
        ("side-illustration-v1", "Side-view illustration", "SIDE", side,
         "Project-authored side-view vehicle illustration with a rust-colored drawn panel scuff; not an auction photo."),
        ("rear-illustration-v1", "Rear-view illustration", "REAR", rear,
         "Project-authored rear-view vehicle illustration with no highlighted cosmetic feature; hidden condition is not depicted and this is not an auction photo."),
    ]
    for asset_id, title, view, painter, alt_text in specs:
        image = painter()
        output = ROOT / f"{asset_id}.png"
        image.save(output, format="PNG", compress_level=9, optimize=False)
        raw = output.read_bytes()
        with Image.open(output) as decoded:
            decoded.verify()
        with Image.open(output) as decoded:
            decoded.load()
            assert decoded.format == "PNG" and decoded.size == (WIDTH, HEIGHT)
        entries.append(dict(
            asset_id=asset_id, filename=output.name, sha256=hashlib.sha256(raw).hexdigest(),
            width=WIDTH, height=HEIGHT, mime_type="image/png", title=title,
            view_label=view, alt_text=alt_text, source_kind="SELF_AUTHORED_FIXTURE",
            author="Project-authored procedural test fixture",
            rights_reference="docs/inspection-fixtures.md",
            reviewed_by="Project fixture author; procedural illustration review",
            permissions=dict(image_display=True, mock_preview=True, ai_inference=False, model_training=False),
            revoked=False, expires_at=None,
        ))
    (ROOT / "manifest.json").write_text(json.dumps(dict(schema_version="1", assets=entries), indent=2) + "\n", encoding="utf-8")
    return entries


if __name__ == "__main__":
    for entry in generate():
        print(f"{entry['asset_id']} {entry['sha256']}")
