def font(size: int):
    # Pillow bundles this font; no machine-specific/system font is loaded.
    return ImageFont.load_default(size=size)


def label(draw: ImageDraw.ImageDraw, xy, text: str, size=18, fill=INK):
    draw.text(xy, text, font=font(size), fill=fill)


def sheet(number: str, title: str, subtitle: str):
    image = Image.new("RGB", (WIDTH, HEIGHT), PAPER)
    draw = ImageDraw.Draw(image)
    label(draw, (36, 27), f"{number} / {title}", 24, OLIVE)
    label(draw, (36, 64), "SYNTHETIC ILLUSTRATION", 15, MUTED)
    draw.rectangle((697, 31, 924, 64), outline=RUST, width=1)
    label(draw, (712, 39), "NOT AUCTION PHOTO", 15, RUST)
    draw.line((36, 94, 924, 94), fill=INK, width=1)
    draw.ellipse((175, 438, 800, 476), fill="#E1E0D7")
    draw.line((96, 469, 864, 469), fill=RULE, width=1)
